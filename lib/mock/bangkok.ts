// ── helpers ──────────────────────────────────────────────────────────────────
const rv = (
  rating: number,
  dateISO: string,
  origin: ReviewOrigin,
  text: string,
  language?: string,
): Review => ({
  rating,
  dateISO,
  looksLocalOrTourist: origin,
  text,
  language: language ?? (origin === "local" ? "th" : "en"),
});

/** Smooth relative-busyness curve from a set of peak hours (0–23). */
function busyCurve(centers: number[], spread = 2, floor = 0.05, peak = 0.9): number[] {
  return Array.from({ length: 24 }, (_, h) => {
    let v = floor;
    for (const c of centers) v = Math.max(v, peak * Math.exp(-((h - c) ** 2) / (2 * spread * spread)));
    return Math.round(v * 100) / 100;
  });
}

